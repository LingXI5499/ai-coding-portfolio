const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const root = path.resolve(__dirname, '..');
const base = process.env.LAB_URL || 'http://127.0.0.1:4173/';
(async () => {
  const browser = await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH});
  const page = await browser.newPage({viewport:{width:1440,height:1050},acceptDownloads:true});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base);
  await page.waitForFunction(()=>document.getElementById('runStatus').textContent==='预览已加载');
  const audit=await page.evaluate(()=>{
    const declarations=demos.flatMap(demo=>traceCss({html:demo.html,css:demo.css,js:demo.js}).map(row=>({...row,id:demo.id})));
    const props=[...new Set(declarations.map(row=>row.property))];
    const attrs=demos.flatMap(demo=>traceHtml(demo).flatMap(row=>row.attrs.map(attr=>({name:attr.name,tag:row.tag,id:demo.id}))));
    const missingProps=props.filter(name=>!name.startsWith('--')&&!CSS_HELP[name]);
    const missingNotes=demos.filter(demo=>!demo.detail?.terms.length||!demo.detail?.steps.length).map(d=>d.id);
    const orderProblems=demos.flatMap(demo=>demo.prerequisites.filter(id=>!validIds.has(id)||demos.find(d=>d.id===id).chapterIndex>=demo.chapterIndex).map(id=>({lesson:demo.id,prerequisite:id})));
    const offsets=declarations.filter(row=>row.language==='css'&&!demos.find(d=>d.id===row.id).css.slice(row.offset).startsWith(row.property));
    return {lessons:demos.length,chapters:LEARNING_CHAPTERS.length,properties:props.length,declarations:declarations.length,attributeOccurrences:attrs.length,missingProps,missingNotes,orderProblems,badOffsets:offsets.map(row=>({id:row.id,property:row.property,offset:row.offset})),unknownAttrs:[...new Set(attrs.filter(a=>!HTML_ATTRIBUTE_HELP[a.name]&&!/^data-|^aria-/.test(a.name)).map(a=>a.name))]};
  });
  assert.deepEqual(audit.missingProps,[],'实际使用的CSS属性都有释义');
  assert.deepEqual(audit.missingNotes,[],'每个实验都有具体阅读说明');
  assert.deepEqual(audit.orderProblems,[],'前置课程必须早于当前章节');
  assert.deepEqual(audit.badOffsets,[],'声明定位必须指向作者实际源码');
  const load=async id=>{await page.evaluate(id=>switchDemo(id),id);await page.waitForFunction(()=>document.getElementById('runStatus').textContent==='预览已加载');};
  await load('css-syntax');
  assert.ok((await page.locator('.trace-card').first().locator('summary').textContent()).includes('#c2410c'),'保留作者颜色写法');
  const card=page.locator('.trace-card').first();
  await card.locator('summary').click();
  await card.getByRole('button',{name:'高亮目标并测量'}).click();
  await page.waitForFunction(()=>document.getElementById('traceResult').textContent.includes('rgb(194, 65, 12)'));
  await card.getByRole('button',{name:'定位到源码'}).click();
  assert.ok(await page.locator('#codeEditor').evaluate(node=>node.value.slice(node.selectionStart,node.selectionEnd).startsWith('color:')));
  const before=await page.locator('#traceResult').textContent();
  await page.evaluate(()=>window.postMessage({type:'flab-inspect-result',token:runToken,request:traceRequest,text:'伪造结果'},'*'));
  assert.equal(await page.locator('#traceResult').textContent(),before,'宿主窗口伪造消息不能冒充预览结果');
  await load('css-normal-flow');
  const frame=page.frameLocator('#preview');
  const gap=await frame.locator('.box').evaluateAll(nodes=>nodes[1].getBoundingClientRect().top-nodes[0].getBoundingClientRect().top);
  assert.equal(gap,40);
  await page.locator('#cssTab').click();
  const flowCss=await page.locator('#codeEditor').inputValue();
  await page.locator('#codeEditor').fill(flowCss.replace('height: 40px','height: 60px'));
  await page.locator('#runBtn').click();
  await page.waitForFunction(()=>document.getElementById('runStatus').textContent==='预览已加载');
  assert.equal(await frame.locator('.box').evaluateAll(nodes=>nodes[1].getBoundingClientRect().top-nodes[0].getBoundingClientRect().top),60);
  await page.locator('#resetBtn').click();
  await load('css-flow-position');
  const rects=async()=>frame.locator('.parent').evaluate(node=>({height:node.getBoundingClientRect().height,cTop:node.children[2].getBoundingClientRect().top,bTop:node.children[1].getBoundingClientRect().top}));
  const normal=await rects(); assert.equal(normal.height,124);
  await frame.locator('#mode').selectOption('relative');
  const relative=await rects();assert.equal(relative.height,124);assert.equal(relative.cTop,normal.cTop);assert.equal(relative.bTop,normal.bTop+20);
  await frame.locator('#mode').selectOption('absolute');
  const absolute=await rects();assert.equal(absolute.height,84);assert.equal(absolute.cTop,normal.cTop-40);
  await frame.locator('#mode').selectOption('fixed');assert.equal((await rects()).height,84);
  await load('css-inline-boxes');
  const boxes=await frame.locator('.row').evaluateAll(rows=>rows.map(row=>[...row.children].map(n=>({width:n.getBoundingClientRect().width,height:n.getBoundingClientRect().height,top:n.getBoundingClientRect().top}))));
  assert.equal(boxes[0][0].width,100);assert.equal(boxes[0][1].top-boxes[0][0].top,40);assert.ok(boxes[1][0].width<100);assert.equal(boxes[2][0].width,100);assert.equal(boxes[2][0].top,boxes[2][1].top);
  await load('layout-wireframe-960');
  const wire=await frame.locator('.page').evaluate(node=>{
    const size=n=>({width:n.getBoundingClientRect().width,height:n.getBoundingClientRect().height});
    return {page:size(node),header:[...node.querySelector('.header').children].map(size),left:size(node.querySelector('.left')),right:size(node.querySelector('.right')),top:[...node.querySelector('.top').children].map(size),bottom:[...node.querySelector('.bottom').children].map(size),side:[...node.querySelector('.right').children].map(size)};
  });
  assert.deepEqual(wire.page,{width:960,height:610});assert.deepEqual(wire.header.map(r=>r.width),[200,540,200]);assert.deepEqual(wire.left,{width:750,height:410});assert.deepEqual(wire.right,{width:200,height:410});assert.ok(wire.top.every(r=>r.width===370&&r.height===200));assert.ok(wire.bottom.every(r=>r.width===180&&r.height===200));assert.ok(wire.side.every(r=>r.width===200&&r.height===130));
  await frame.locator('#adaptive').check();
  await page.getByRole('button',{name:'手机',exact:false}).first().click();
  await page.waitForFunction(()=>document.getElementById('preview').getBoundingClientRect().width<=390);
  assert.ok(await frame.locator('.page').evaluate(node=>node.getBoundingClientRect().width<=390));
  await frame.locator('#adaptive').uncheck();assert.equal(await frame.locator('.page').evaluate(n=>n.getBoundingClientRect().width),960,'固定模式小屏仍960，不偷换图示尺寸');
  await page.getByRole('button',{name:'电脑',exact:false}).first().click();
  await page.waitForFunction(()=>document.getElementById('preview').getBoundingClientRect().width>390);
  const pendingDownload = page.waitForEvent('download');
  await page.locator('#downloadBtn').click();
  const download=await pendingDownload;
  await download.saveAs(path.join(root,'verification','wireframe-export.html'));
  const exported=await page.evaluate(()=>buildHtml(current(),true));
  assert.ok(!exported.includes('flab-inspect-request'),'导出不含工作台测量桥');
  await page.setContent(exported);
  assert.deepEqual(await page.locator('.page').evaluate(n=>({width:n.getBoundingClientRect().width,height:n.getBoundingClientRect().height})),{width:960,height:610});
  await page.goto(base);await page.waitForFunction(()=>typeof demos!=='undefined');
  await page.locator('#roadmapBtn').click();assert.equal(await page.locator('.chapter-roadmap > details').count(),24);
  await page.getByRole('button',{name:'上传教程的顺序、实验对应与现代纠错'}).click();
  assert.ok((await page.locator('#dialogContent').textContent()).includes('Application Cache已废弃'));
  await page.getByRole('button',{name:'标签、元素、属性：先读懂一行 HTML',exact:true}).first().click();assert.equal(await page.locator('#learningDialog').evaluate(n=>n.open),false);
  for(const width of [390,768,1440]) {
    await page.setViewportSize({width,height:1000});await load('css-normal-flow');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'新说明UI不造成横向溢出');
    if(width===390) {
      await page.waitForFunction(()=>document.getElementById('sidebar').getBoundingClientRect().right<=0);
      await page.screenshot({path:path.join(root,'verification','teaching-mobile.png'),fullPage:false});
    }
  }
  await page.setViewportSize({width:1440,height:1050});await load('css-flow-position');await page.screenshot({path:path.join(root,'verification','teaching-desktop.png'),fullPage:false});
  const local=await browser.newPage();await local.goto('file:///'+root.replace(/\\/g,'/')+'/index.html#lesson=layout-wireframe-960');await local.waitForFunction(()=>document.getElementById('runStatus').textContent==='预览已加载');assert.equal(await local.frameLocator('#preview').locator('.page').evaluate(n=>n.getBoundingClientRect().width),960);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(root,'verification','teaching-report.json'),JSON.stringify({date:new Date().toISOString(),result:'passed',...audit,flow:{normal,relative,absolute},wireframe:wire,errors},null,2));
  await browser.close();console.log(JSON.stringify({result:'passed',...audit}));
})().catch(error=>{console.error(error);process.exit(1);});
