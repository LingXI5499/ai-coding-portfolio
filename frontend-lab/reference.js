/* 技术速查：按用途组织，链接到规范参考，不以实验数量代替覆盖范围。 */
const REFERENCES = [];
function referenceGroup(cat, group, rows) {
  for (const [name, description, example, path] of rows) {
    REFERENCES.push({
      cat,
      group,
      name,
      description,
      example,
      doc:
        MDN +
        (path ||
          (cat === 'html' && /^h[1-6]$/.test(name)
            ? 'Web/HTML/Reference/Elements/Heading_Elements'
            : null) ||
          (cat === 'html'
            ? 'Web/HTML/Reference/Elements/' + name
            : cat === 'css'
              ? 'Web/CSS/Reference/Properties/' + name
              : 'Web/JavaScript/Reference/' + name)),
    });
  }
}
